def stabilize_cash_metrics(metrics,path,trades,bil):
    risky=trades[trades.asset!='BIL']
    cash_only=bool((risky.weight_close==0).all() and (risky.trade_notional==0).all())
    metrics['cash_only_by_holdings']=cash_only
    metrics['raw_excess_return_before_cash_identity']=metrics['annual_excess_return']
    metrics['raw_excess_volatility_before_cash_identity']=metrics['annual_excess_volatility']
    if cash_only:
        e=path.net_return.to_numpy()-bil.reindex(path.date).to_numpy()
        require(np.isfinite(e).all() and np.max(np.abs(e))<=1e-12 and path.cost_fraction.abs().max()<=1e-12,
                'Cash-only account differs materially from BIL; do not normalize')
        metrics.update(annual_excess_return=0.,annual_excess_volatility=0.,daily_sharpe=None,
                       sharpe_status='undefined_zero_excess_volatility_cash_only')
        metrics['calmar']=0. if metrics['max_drawdown']!=0 else None
    return metrics


def summarize():
    from .data import read_prices
    prices,_=read_prices();bil=prices['BIL'].adj_close.pct_change(fill_method=None)
    nav,trades=[pd.read_parquet(OUT/f'{x}.parquet') for x in ['nav','trades']]
    rows=[]
    for id,g in nav.groupby('id'):
        tr=trades[trades.id==id]
        metrics=stabilize_cash_metrics(account_metrics(g,tr,bil,51),g,tr,bil)
        rows.append({'id':id,**metrics})
    summary=pd.DataFrame(rows).rename(columns={'target_risk_exposure':'post_open_risk_exposure'});summary.to_csv(OUT/'diagnostic_summary.csv',index=False)
    lookup=summary.set_index('id');contrasts=[]
    old=pd.read_csv(ROOT/'results/study/summary.csv')
    alias={'annual_cer':'annual_cer','daily_sharpe':'daily_sharpe','annual_excess_return':'daily_annual_excess_return',
           'max_drawdown':'max_drawdown','annual_cost_fraction':'annual_cost_fraction',
           'annual_turnover_9':'annual_turnover_two_leg','closing_risk_exposure':'average_closing_risk_exposure'}
    for s in specs():
        ref=s['reference_id']
        if ref.startswith('B51_'):
            name=ref.removeprefix('B51_')
            r=old[(old.study=='B')&(old.strategy==name)&(old.cost_bp==5)].iloc[0]
            baseline={k:r[v] for k,v in alias.items()}
        else:baseline=lookup.loc[ref]
        row={'id':s['id'],'reference_id':ref,'effect_type':s['effect_type'],'override_fields':','.join(s['override_fields'])}
        for k in alias:row['delta_'+k]=float(lookup.loc[s['id'],k]-baseline[k])
        contrasts.append(row)
    pd.DataFrame(contrasts).to_csv(OUT/'diagnostic_contrasts.csv',index=False)
    return summary


def classification():
    p=pd.read_parquet(OUT/'predictions.parquet');raw=pd.read_parquet(OUT/'candidate_probabilities.parquet')
    fits=json.loads((OUT/'fits.json').read_text())
    meta={f['key']:f for f in fits}
    for f in json.loads((ROOT/'results/study/fits.json').read_text()):
        if 'A_xgb' in f['metadata']:meta[f['key']]=f['metadata']['A_xgb']
    rows=[]
    for (id,asset),g in p.groupby(['id','asset']):
        g=g.sort_values('target_date');y=g.label.to_numpy(int);prob=np.column_stack([g.p0,g.p1]);w=monthly_weights(pd.DatetimeIndex(g.target_date))
        priors=np.array([meta[k]['prior'] for k in g.fit_key])
        persistence=np.eye(2)[g.persistence_label.to_numpy(int)]
        trans=y!=g.persistence_label.to_numpy(int)
        row={'id':id,'asset':asset,'n':len(g),'observed_months':g.target_date.dt.to_period('M').nunique(),
             'weighted_accuracy':float(np.average(prob.argmax(axis=1)==y,weights=w)),
             'weighted_logloss':float(log_loss(y,prob,labels=[0,1],sample_weight=w)),
             'frequency_accuracy':float(np.average(priors.argmax(axis=1)==y,weights=w)),
             'frequency_logloss':float(log_loss(y,priors,labels=[0,1],sample_weight=w)),
             'persistence_accuracy':float(np.average(persistence.argmax(axis=1)==y,weights=w)),
             'persistence_logloss':float(log_loss(y,persistence,labels=[0,1],sample_weight=w)),
             'transition_n':int(trans.sum()),
             'transition_accuracy':float(np.average((prob.argmax(axis=1)==y)[trans],weights=w[trans])) if trans.any() else None,
             'p0_q05':float(g.p0.quantile(.05)),'p0_q50':float(g.p0.quantile(.5)),'p0_q95':float(g.p0.quantile(.95)),
             'label_path':'own_refitted_JM' if id=='P01' else ('reselected_A_JM' if id=='S01' else 'fixed_A_selected_JM')}
        if id in set(raw.id):
            r=raw[raw.id==id].set_index(['asset','train_end','penalty','target_date'])
            idx=pd.MultiIndex.from_frame(g[['asset','train_end','penalty','target_date']])
            values=r.reindex(idx)[['raw_p0','raw_p1']].to_numpy()
            require(np.isfinite(values).all(),'Missing selected raw classifier probability')
            mass_error=float(np.abs(values.sum(axis=1)-1).max())
            require(mass_error<=np.finfo(np.float32).eps,'Raw binary probabilities exceed native precision')
            row['raw_mass_max_abs_error']=mass_error
            canonical=np.column_stack([values[:,0],1-values[:,0]])
            row['raw_weighted_logloss']=float(log_loss(y,canonical,labels=[0,1],sample_weight=w))
        rows.append(row)
    pd.DataFrame(rows).to_csv(OUT/'classification.csv',index=False)
    training=pd.DataFrame([{k:f.get(k) for k in ['id','asset','asof','penalty','key','n_train','n_months','sample_weight_sum',
        'single_class','training_weighted_logloss','training_unweighted_logloss','tree_count','max_tree_depth','mean_tree_depth','stump_count']} for f in fits])
    training.to_csv(OUT/'training_diagnostics.csv',index=False)


