import assert from 'node:assert/strict';
import { loadConfig } from './config.js';
import { makeDemo } from './demo.js';
import { observationSchema, decisionSchema } from './types.js';
import { buildPanel, predictionSamples } from './features/panel.js';
import { evaluateGate, requireGate } from './validation/gate.js';
import { explanatoryAnalysis } from './econometrics/analysis.js';
import { walkForward } from './forecasting/walkForward.js';
import { evaluateForecasts } from './evaluation/bootstrap.js';

const { experiment, contract, features } = await loadConfig('configs/demo.yaml', 'configs/demo_contract.yaml');
const { observations, decisions } = makeDemo();
observations.forEach((r) => observationSchema.parse(r));
decisions.forEach((r) => decisionSchema.parse(r));
const panel = buildPanel(observations, decisions, features);
const samples = predictionSamples(panel, observations, features.map((f) => f.id), experiment.primary_target);
const gate = evaluateGate(contract, experiment, features, observations, decisions, samples);
requireGate(gate);
assert.equal(gate.label, 'SYNTHETIC_DEMO');
assert.equal(gate.status, 'reduced');
const explanation = explanatoryAnalysis(buildPanel(observations, decisions, features, true), features, experiment);
assert.equal(explanation.h1.length, 2);
const forecasts = walkForward(samples, experiment);
const evaluation = evaluateForecasts(forecasts, experiment);
assert.equal(evaluation.summary.length, 4);
assert.equal(evaluation.summary[0].oos_r2, 0);
assert.equal(forecasts.length, 131 * 4);
assert(forecasts.every((r) => r.last_train_period < r.period));
console.log(`PASS · synthetic only · ${observations.length} observations · ${forecasts.length / 4} fixed OOS months · 4 models · P0/P1/P2/P4 integration`);
